#!/usr/bin/env python3
"""
build_india_with_gemini.py

Usage examples:
  # Download datameet CSVs and generate SQL (no Gemini):
  python3 build_india_with_gemini.py --download --output Learn/database/sql/india_with_gemini.sql

  # Same but ask Gemini (Google Generative) to resolve missing district->state mappings (requires GEMINI_API_KEY):
  GEMINI_API_KEY=your_key python3 build_india_with_gemini.py --download --use-gemini --output Learn/database/sql/india_with_gemini.sql

Notes:
 - GEMINI_API_KEY should be provided via environment variable. The script does NOT transmit the key to anyone; it uses it to call the Generative Language REST endpoint.
 - You can set GEMINI_MODEL env var to the model name (default: text-bison-001). Adjust per your Google/Vertex/Generative API setup.
 - The script writes a mapping report JSON next to the output SQL file.
"""

