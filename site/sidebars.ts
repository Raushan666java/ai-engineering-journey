import fs from 'fs';
import path from 'path';
import type {SidebarsConfig} from '@docusaurus/plugin-content-docs';

const buildOnly = process.env.BUILD_ONLY?.trim();

const sidebars: SidebarsConfig = {
  // index.md declares `sidebar_id: placementSidebar`. In a part build that
  // course is excluded, so the id has to keep resolving to *something* or
  // rendering /course-overview throws "Can't find any sidebar with id".
  // A part build only needs one valid sidebar to exist, so alias it to the
  // course being built; the left nav is rebuilt in the full deploy anyway.
  placementSidebar: [
    {
      type: 'autogenerated',
      dirName: `courses/${buildOnly ?? 'ai-engineering-placement'}`,
    },
  ],
};

const coursesDir = path.resolve(process.cwd(), 'docs', 'courses');
// When building in parts, only the course being built is loaded. Referencing a
// course whose docs were excluded makes Docusaurus fail on the sidebar, so the
// list has to be narrowed to match.
if (fs.existsSync(coursesDir)) {
  for (const dir of fs.readdirSync(coursesDir)) {
    const full = path.join(coursesDir, dir);
    if (!fs.statSync(full).isDirectory()) continue;
    if (dir === 'ai-engineering-placement') continue;
    if (buildOnly && dir !== buildOnly) continue;
    (sidebars as Record<string, unknown>)[`course-${dir}`] = [
      {
        type: 'autogenerated',
        dirName: `courses/${dir}`,
      },
    ];
  }
}

export default sidebars;
