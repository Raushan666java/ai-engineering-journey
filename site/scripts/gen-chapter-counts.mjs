#!/usr/bin/env node
/**
 * Write `src/data/chapter-counts.ts` from the deploy tree.
 *
 * The course grid on /courses lists 60 course names and nothing else, so a
 * reader cannot tell a 5-chapter overview from a 392-chapter course. Counting
 * at build time keeps the number honest instead of hand-maintained.
 *
 *   node scripts/gen-chapter-counts.mjs
 */

import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve('docs', 'courses');
const OUT = path.resolve('src', 'data', 'chapter-counts.ts');
const NOT_A_CHAPTER = /^(index|readme|visual-notes|template)\.mdx?$/i;

function countChapters(dir) {
  let chapters = 0;
  let words = 0;
  const walk = (d) => {
    for (const entry of fs.readdirSync(d, {withFileTypes: true})) {
      const full = path.join(d, entry.name);
      if (entry.isDirectory()) {
        if (entry.name === 'node_modules' || entry.name.startsWith('.')) continue;
        walk(full);
      } else if (/\.mdx?$/.test(entry.name) && !NOT_A_CHAPTER.test(entry.name)) {
        chapters++;
        const text = fs.readFileSync(full, 'utf8');
        words += (text.match(/\S+/g) || []).length;
      }
    }
  };
  walk(dir);
  return {chapters, words};
}

const rows = [];
for (const entry of fs.readdirSync(ROOT, {withFileTypes: true})) {
  if (!entry.isDirectory()) continue;
  const full = path.join(ROOT, entry.name);
  const {chapters, words} = countChapters(full);
  rows.push({slug: entry.name, chapters, words});
}

rows.sort((a, b) => b.chapters - a.chapters);

const totals = rows.reduce(
  (acc, r) => ({chapters: acc.chapters + r.chapters, words: acc.words + r.words}),
  {chapters: 0, words: 0},
);

const lines = [
  '/**',
  ' * Generated by scripts/gen-chapter-counts.mjs — do not edit by hand.',
  ' *',
  ' * Counts exclude index.md, readme and visual-notes, which are navigation',
  ' * pages rather than teaching chapters.',
  ' */',
  '',
  'export interface CourseSize {',
  '  chapters: number;',
  '  words: number;',
  '}',
  '',
  'export const courseSizes: Record<string, CourseSize> = {',
  ...rows.map(
    (r) =>
      `  ${JSON.stringify(r.slug)}: {chapters: ${r.chapters}, words: ${r.words}},`,
  ),
  '};',
  '',
  `export const corpusSize = {courses: ${rows.length}, chapters: ${totals.chapters}, words: ${totals.words}};`,
  '',
];

fs.writeFileSync(OUT, lines.join('\n'), 'utf8');

console.log(`wrote ${OUT}`);
console.log(`courses  : ${rows.length}`);
console.log(`chapters : ${totals.chapters}`);
console.log(`words    : ${totals.words.toLocaleString('en-US')}`);
console.log('\nlargest:');
for (const r of rows.slice(0, 5)) console.log(`  ${String(r.chapters).padStart(4)}  ${r.slug}`);
